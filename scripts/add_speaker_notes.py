from pptx.opc.constants import RELATIONSHIP_TYPE as RT

def add_notes(slide, text):
    """Robust notes addition — tries native API then XML fallback."""
    try:
        notes_slide = slide.notes_slide
        tf = notes_slide.notes_text_frame
        tf.clear()
        tf.paragraphs[0].text = text
        for p in tf.paragraphs:
            p.font.size = Pt(10)
        return True
    except (ValueError, KeyError) as e1:
        pass

    # Fallback: manually create notes relationship via XML
    try:
        from lxml import etree
        slide_part = slide.part
        # Create notes slide XML
        nsmap = {
            'p': 'http://schemas.openxmlformats.org/presentationml/2006/main',
            'a': 'http://schemas.openxmlformats.org/drawingml/2006/main',
            'r': 'http://schemas.openxmlformats.org/officeDocument/2006/relationships',
        }
        notes_xml = (
            f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            f'<p:notes xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"'
            f' xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"'
            f' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            f'<p:cSld><p:spTree><p:sp><p:nvSpPr><p:cNvPr id="1" name="Notes"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
            f'<p:spPr/><p:txBody><a:bodyPr/><a:p><a:r><a:rPr lang="zh-CN" sz="1000"/><a:t>{text}</a:t></a:r></a:p></p:txBody>'
            f'</p:sp></p:spTree></p:cSld></p:notes>'
        )
        notes_element = etree.fromstring(notes_xml.encode('utf-8'))
        from pptx.parts.notes import NotesSlidePart
        from pptx.opc.packuri import PackURI
        # Generate unique part name
        import random
        part_name = f'/ppt/notesSlides/notesSlide{slide.slide_id}_{random.randint(1000,9999)}.xml'
        notes_part = NotesSlidePart(
            PackURI(part_name),
            'application/vnd.openxmlformats-officedocument.presentationml.notesSlide+xml',
            notes_element,
            slide_part.package,
        )
        slide_part.relate_to(notes_part, RT.NOTES_SLIDE)
        return True
    except Exception as e2:
        print(f"  WARNING: Slide {slide.slide_id} notes failed (native={e1}, xml={e2})")
        return False

