def clean(s):
    if not isinstance(s, str):
        s = str(s)
    result = []
    for ch in s:
        cp = ord(ch)
        if cp < 0x20 and cp not in (9, 10, 13):
            continue
        if 0x7F <= cp <= 0x9F or 0xD800 <= cp <= 0xDFFF or cp in (0xFFFE, 0xFFFF):
            continue
        result.append(ch)
    return ''.join(result)


