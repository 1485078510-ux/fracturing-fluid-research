def add_title(text, level=0):
    """添加标题"""
    if level == 0:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        run = p.add_run(text)
        run.bold = True
        run.font.size = Pt(16)
        run.font.name = '黑体'
        run.element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')
        return p
    else:
        heading = doc.add_heading(text, level=level)
        for run in heading.runs:
            run.font.name = '黑体'
            run.element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')
        return heading

def add_para(text, indent=True, bold=False):
    """添加正文段落"""
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    else:
        p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(text)
    run.font.name = '宋体'
    run.font.size = Pt(12)
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    if bold:
        run.bold = True
    return p

def add_section_heading(text):
    """添加一级标题"""
    return add_title(text, level=1)

def add_subsection_heading(text):
    """添加二级标题"""
    return add_title(text, level=2)

def add_empty_line():
    """添加空行"""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    return p

