add_para('关井破胶阶段：停泵关井，在储层温度（60~150°C）下维持密闭状态6~48小时。在此阶段，交联冻胶中的有机硼交联键在破胶剂（过硫酸铵）作用下发生氧化断裂，聚合物网络解体；同时，改性荧光粉外层的PEG物理屏蔽层在破胶剂氧化环境与储层温度的协同作用下，经历以下三个过程而逐步脱附降解：（i）过硫酸铵热分解产生的硫酸根自由基（SO₄•⁻）攻击PEG醚键（C-O-C），引发氧化链断裂，生成低分子量PEG碎片和含氧低聚物；（ii）低分子量产物的水溶性显著增大，倾向于从荧光粉表面向水相溶解释放；（iii）破胶剂分解产生的酸性微环境（局部pH下降）促使PEG醚氧原子的质子化程度增加，削弱PEG与内层硅烷偶联剂的物理吸附作用。PEG外层脱附后，暴露出内层KH550硅烷偶联剂的活性氨基官能团（-NH₂），活性氨基与裂缝壁面砂岩的硅羟基（Si-OH）通过静电吸引、氢键和/或化学缩合（形成Si-O-Si或Si-N键）实现牢固锚定；')
add_para('返排阶段：开井返排，返排液携带破胶后的聚合物残渣和少量未锚定的游离荧光粉颗粒排出井筒，已锚定于裂缝壁面的荧光粉则牢固保留；')
add_para('取心与检测阶段：在压后取心作业中取出含裂缝的岩心，在紫外光源（波长350~380 nm，优选365 nm）照射下直接观察或拍照记录裂缝壁面的荧光分布。荧光分布区域即为压裂液的实际波及区域，可作为裂缝诊断结果的可实物验证直接证据。')

add_para('进一步地，在注入阶段中，荧光母液的在线添加可在前置液段、携砂液段或顶替液段中的一段或多段中进行。优选在前置液段和携砂液段中连续添加，以形成从裂缝入口到尖端的完整荧光标记，从而全面反映压裂液在整个裂缝网络中的波及范围。')
add_para('进一步地，在关井破胶阶段中，所述改性荧光粉从"分散态"向"锚定态"的功能切换利用压裂施工自身的时间序列（注入→关井→返排）驱动，以压裂液配方中原有的过硫酸铵破胶剂作为脱附触发条件，无需额外添加任何专用触发剂。以此方式，本发明将压裂施工作业的工序结构创造性地转化为颗粒表面化学的功能转化序列，实现了与现有压裂工艺的无缝兼容。')

