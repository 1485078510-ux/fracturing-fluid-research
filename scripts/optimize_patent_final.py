def find_para(doc, keyword):
    for i, p in enumerate(doc.paragraphs):
        if p.text and keyword in p.text:
            return i
    return None

def mk_para(text, font_size='24'):
    ns = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
    p = etree.Element(f'{{{ns}}}p')
    pPr = etree.SubElement(p, f'{{{ns}}}pPr')
    ind = etree.SubElement(pPr, f'{{{ns}}}ind')
    ind.set(f'{{{ns}}}firstLine', '480')
    r = etree.SubElement(p, f'{{{ns}}}r')
    rPr = etree.SubElement(r, f'{{{ns}}}rPr')
    rf = etree.SubElement(rPr, f'{{{ns}}}rFonts')
    rf.set(f'{{{ns}}}eastAsia', '宋体')
    rf.set(f'{{{ns}}}ascii', 'Times New Roman')
    rf.set(f'{{{ns}}}hAnsi', 'Times New Roman')
    sz = etree.SubElement(rPr, f'{{{ns}}}sz')
    sz.set(f'{{{ns}}}val', font_size)
    szC = etree.SubElement(rPr, f'{{{ns}}}szCs')
    szC.set(f'{{{ns}}}val', font_size)
    t = etree.SubElement(r, f'{{{ns}}}t')
    t.text = text
    t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    return p

def mk_heading(text):
    ns = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
    p = etree.Element(f'{{{ns}}}p')
    pPr = etree.SubElement(p, f'{{{ns}}}pPr')
