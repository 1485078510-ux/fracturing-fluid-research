doc = Document(SRC)

# 统计处理情况
total_changes = 0
matched_paras = 0

for para in doc.paragraphs:
    para_text = para.text

    # 跳过空段落和标题
    if not para_text.strip():
        continue

    # 查找匹配的修改规则
    matched_replacements = []
    for keyword, replacements in ALL_CHANGES:
        if keyword in para_text or any(old in para_text for old, new in replacements):
            # 只收集本段中old文本实际存在的替换
            for old, new in replacements:
                if old in para_text:
                    matched_replacements.append((old, new))

    if matched_replacements:
        # 保留字体信息
        font_info = get_para_font_info(para)

        # 去重（按old_str）
        unique_replacements = []
        seen_old = set()
        for old, new in matched_replacements:
            if old not in seen_old:
                unique_replacements.append((old, new))
                seen_old.add(old)

        # 应用替换
        success = apply_multi_replace_with_highlight(para, unique_replacements, font_info)
        if success:
            matched_paras += 1
            total_changes += len(unique_replacements)

# 保存
doc.save(DST)

