def add_highlight_to_run(run, color="yellow"):
    """为run添加高亮背景"""
    rPr = run._element.get_or_add_rPr()
    highlight = OxmlElement('w:highlight')
    highlight.set(qn('w:val'), color)
    rPr.append(highlight)

def get_para_font_info(para):
    """获取段落中第一个run的字体信息作为参考"""
    if para.runs:
        r = para.runs[0]
        return {
            'size': r.font.size,
            'bold': r.font.bold,
            'name': r.font.name,
            'color': r.font.color.rgb if r.font.color and r.font.color.rgb else None
        }
    return {'size': Pt(12), 'bold': None, 'name': '宋体', 'color': None}

def apply_font(run, font_info):
    """将字体信息应用到run"""
    if font_info['size']:
        run.font.size = font_info['size']
    if font_info['bold'] is not None:
        run.font.bold = font_info['bold']
    if font_info['name']:
        run.font.name = font_info['name']
    if font_info['color']:
        run.font.color.rgb = font_info['color']

def apply_multi_replace_with_highlight(para, replacements, font_info=None):
    """
    在段落中应用多处替换，仅高亮标注被替换的新内容。

    replacements: list of (old_str, new_str) tuples
    算法:
    1. 获取段落原文
    2. 按位置排序所有替换
    3. 将原文切分为 [保留段, 新内容段, 保留段, 新内容段, ...]
    4. 为每个段创建run，新内容段添加黄色高亮
    """
    if not replacements:
        return False

    # 验证所有old_str都在文本中
    valid_replacements = [(o, n) for o, n in replacements if o in para.text]
    if not valid_replacements:
        return False

    full_text = para.text
    if not font_info:
        font_info = get_para_font_info(para)

    # 找到每个替换的起止位置，按位置排序
    segments = []  # list of (start, end, new_text)
    for old, new in valid_replacements:
        start = full_text.find(old)
        if start >= 0:
            segments.append((start, start + len(old), new))

    segments.sort(key=lambda x: x[0])

    # 处理重叠（如有重叠则合并相邻段）
    merged = []
    for seg in segments:
        if merged and seg[0] < merged[-1][1]:
            # 有重叠，扩展上一个段
            prev = merged.pop()
            merged.append((prev[0], max(prev[1], seg[1]), ""))
        else:
            merged.append(seg)

    # 构建最终的run序列
    run_parts = []  # (text, is_highlighted)
    cursor = 0
    for start, end, new_text in merged:
        # 前面未修改的部分
        if cursor < start:
            run_parts.append((full_text[cursor:start], False))
        # 修改后的新内容
        run_parts.append((new_text, True))
        cursor = end

    # 尾部剩余未修改部分
    if cursor < len(full_text):
        run_parts.append((full_text[cursor:], False))

    if not run_parts:
        return False

    # 清除原有runs
    for run in list(para.runs):
        run._element.getparent().remove(run._element)

    # 创建新的runs
    for text, highlighted in run_parts:
        if not text:
            continue
        new_run = para.add_run(text)
        apply_font(new_run, font_info)
        if highlighted:
            add_highlight_to_run(new_run, "yellow")

    return True

