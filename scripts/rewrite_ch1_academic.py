    '丧失[46]。表面包覆是解决这一问题的标准工程手段。无机包覆路线方面，Qi等（2017）通过尿素水解法'
    '在荧光粉表面原位沉积了致密SiO₂层（≥5 wt%）[47]；Karacaoglu等（2020）采用原子层沉积（ALD）技术'
    '在荧光粉表面沉积约10 nm Al₂O₃或约12 nm TiO₂薄膜，包覆后48小时浸水磷光得以保持[46]；Deng等'
    '（2013）提出了燃烧法原位形成MAl₂B₂O₇致密层的方案[48]。有机改性路线方面，Urakawa等（2020）发现'
    '硅烷偶联剂处理可使荧光粉发光强度提升10%~20%[49]；Lyu等（2020）以KH570为桥联剂构建了SiO₂-聚合物'
    '复合壳层，实现了耐水性和有机相容性的平衡[50]。',

    '然而，上述包覆方案均面向涂料、塑料和油墨等常压常温应用场景开发，其性能评价标准（如常温水浸48小时'
    '不丧失磷光）与压裂液的工程环境（60~150°C、矿化度0~100 g/L、pH 3~11、过硫酸铵氧化体系）存在'
    '根本性差异。面向压裂液工程的系统环境适应性验证，目前尚属空白。更为关键的是，压裂工程对颗粒表面'
    '化学提出了一种独特的时序功能需求：注入期间，颗粒需在HPG基液中保持均匀分散（以颗粒间排斥力为主导）；'
    '关井破胶期间，颗粒需从分散态向锚定态切换（以颗粒-壁面吸引力为主导）；返排期间及以后，颗粒需牢固'
    '附着于裂缝壁面（抵抗流体剪切力）。如何用单一的表面改性方案协调上述三种在不同时间节点上被激活的、'
    '部分相互矛盾的功能需求，是一个兼具基础胶体科学意义和工程应用价值的核心问题。',

