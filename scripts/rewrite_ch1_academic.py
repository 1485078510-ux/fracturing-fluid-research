    '1.2.4  胍胶压裂液体系',

    '本研究的荧光示踪材料以HPG胍胶压裂液为载体流体。示踪材料必须与该体系在化学上兼容，因此有必要对'
    '胍胶压裂液的化学组成、交联机理、破胶机制和性能评价标准进行概要梳理。',

    '胍胶是从瓜尔豆胚乳中提取的天然半乳甘露聚糖多糖，主链由β-1,4-糖苷键连接的甘露糖单元组成，侧链为'
    'α-1,6-糖苷键连接的半乳糖单元，甘露糖/半乳糖比值约为1.6~1.8:1。分子链上密集分布的顺式邻二醇基团'
    '是硼酸根离子的配位交联位点，高密度的交联位点是胍胶成为高效压裂液稠化剂的化学基础。羟丙基胍胶（HPG）'
    '是胍胶经环氧丙烷醚化改性的产物，通过甘露糖C-6位引入羟丙基取代基削弱分子间氢键网络，水合速率显著'
    '提升，水不溶物含量由天然胍胶的5~10 wt%降至3~5 wt%，已被广泛用作水基压裂液的稠化剂[53,61]。',

    '胍胶压裂液的化学核心是硼酸根离子B(OH)₄⁻与HPG顺式邻二醇基团的可逆配位交联反应。Harris（1993）[58]'
    '系统表征了硼交联HPG冻胶的化学与流变学特征，阐明硼酸根与邻二醇形成1:1和2:1两种配合物，其中2:1'
    '配合物构成分子间交联桥，赋予冻胶粘弹性和支撑剂悬浮能力。Kesavan和Prud\'homme（1992）[59]基于'
    '小振幅振荡剪切实验建立了硼交联瓜尔胶的凝胶化动力学模型，定量揭示了交联密度与硼浓度、pH和温度'
    '之间的函数关系。工程实践中普遍采用有机硼延缓交联剂，其延迟机制基于配体交换：配体在常温下占据硼的'
    '配位位点，阻止硼与HPG邻二醇的过早结合；升温后配体被逐步置换，游离硼酸根释放，交联反应启动。'
    '这一温度触发机制使交联时间具有可控性，有效避免了井筒中过早交联导致的高泵注摩阻。',

    '破胶是压裂液完成携砂造缝使命后的关键步骤，直接影响裂缝导流能力的恢复程度。过硫酸铵（APS）是'
    '60~120°C储层中最为广泛使用的氧化破胶剂，其机理为：APS在水中热分解产生硫酸根自由基SO₄•⁻，自由基'
    '攻击HPG主链的糖苷键和缩醛键，导致聚合物主链断裂、分子量急剧下降，冻胶三维网络坍缩为低粘度液体。'
    'Brannon和Tjon-Joe-Pin（1994）[60]以及Al-Muntasheri（2014）[53]对各类破胶剂的适用温度范围和破胶效率'
    '进行了系统的比较研究。破胶的彻底性是工程上不可妥协的指标：破胶液残渣堵塞支撑剂充填层的孔隙吼道，'
    '可使导流能力降低30%~60%。因此，引入压裂液体系的任何功能添加剂——包括本研究的荧光示踪颗粒——'
    '均须在不显著增加残渣含量和不显著延迟破胶时间的前提条件下实现其设计功能。',

    '中国已建立了较为完善的压裂液性能评价标准体系。SY/T 6376-2008[54]规定了压裂液基液、冻胶和破胶液'
    '的各项性能指标及试验方法；SY/T 5107-2016[55]提供了基液表观粘度、交联时间、耐温耐剪切能力、静态'
    '悬砂和破胶性能的标准化测试流程；SY/T 6540-2002和SY/T 6302-2009分别规范了储层伤害评价和支撑剂'
    '导流能力损害评价方法。本研究严格依据上述标准进行压裂液性能评价，以常规HPG压裂液为参照基线，'
    '定量评估荧光粉引入对各项性能指标的独立影响。',

