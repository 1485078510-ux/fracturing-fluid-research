    '1.3  存在的主要问题',

    '基于上述四个维度的文献调研，可以凝练出一个核心矛盾和三个层次的技术缺口。核心矛盾可表述为：'
    '压裂工程需要裂缝波及范围的直接实物证据，而当前可用的所有方法均只能提供间接推断。三个层次的'
    '技术缺口沿着"材料→工艺→评价"的链条递进展开，分别对应荧光压裂液从概念到应用必须跨越的'
    '三重障碍。',

    '第一，材料层面。高密度微米荧光粉（3.6~4.0 g/cm³）与HPG基液（~1.0 g/cm³）之间存在3~4倍的'
    '密度差。依据Stokes沉降定律估算，13 μm颗粒在HPG基液中的理论沉降速度约为0.5~1.0 mm/min，'
    '在压裂施工2~4小时的注入时间窗口内将发生显著沉降。此外，未经表面改性的SrAl₂O₄在水性环境中'
    '发生水解反应，Guo等（2007）[45]报道了水解导致pH升高和发光性能衰减的现象，且溶出的Sr²⁺和Al³⁺'
    '可能通过配位作用干扰HPG与有机硼的交联反应。文献中已有的包覆方案面向涂料和塑料行业设计，'
    '其工艺条件和性能评价标准与压裂液工程环境不匹配，缺乏面向压裂液工程的系统表面改性方案。',

    '第二，工艺层面。注入阶段要求的颗粒稳定悬浮（以空间位阻或静电排斥为主导）与关井后要求的壁面锚定'
    '（以静电吸引、氢键或化学键合为主导）对颗粒表面化学的需求在本质上是相反的。常规表面包覆策略以'
    '"永久稳定"为设计目标，使颗粒在任何条件下均保持分散态——这恰恰导致颗粒在返排阶段随压裂液一同排出，'
    '无法在裂缝壁面上留下可辨识的标记。需要设计一种"时序响应型"表面结构，使颗粒的表面化学能够响应'
    '压裂施工自身的时间序列（注入→关井→返排）完成从分散到锚定的功能切换。这一设计思想的化学实现'
    '——包括响应触发机制的选择、包覆层降解动力学的调控和功能切换的可逆性——尚未被系统探索。',

    '第三，评价层面。已有荧光示踪研究在评价示踪效果时，普遍跳过了注入剪切、关井破胶和返排冲刷三个'
    '工程必经环节，采用静态浸泡或简单注入后直接成像的方式进行验证。然而，注入阶段的剪切（井筒中约170 '
    's⁻¹量级）可改变颗粒的分散态和团聚状态；关井阶段长达12~24小时的高温静态接触可影响表面包覆层的'
    '化学稳定性；返排阶段的流体冲刷可直接移除弱附着的颗粒。静态条件下的"示踪有效"结论在动态工程条件'
    '下的可推广性缺乏实验支撑。需要建立一套能够完整模拟"注入-关井破胶-返排-取心-成像"全流程的动态'
    '实验方法。',

